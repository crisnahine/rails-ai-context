# frozen_string_literal: true

module RailsAiContext
  module Serializers
    # The stack sections every context file states, each rendered once at the
    # density its file takes: :root or :summary for the root file, :overview for
    # a rules file that stands in for it, :full for the full-mode document.
    module StackSections
      def header_lines(density, title:)
        app = context[:app_name] || "Rails App"
        version = "Rails #{context[:rails_version]} | Ruby #{context[:ruby_version]}"
        case density
        when :root
          notice = SectionFacts.static_notice(context)
          [ "# #{app} - #{title}", "", "> #{version}", "> Generated by rails-ai-context v#{RailsAiContext::VERSION}", *("> #{notice}" if notice), "" ]
        when :overview then [ "# #{app} - #{title}", "", version, "" ]
        else raise ArgumentError, "no header density #{density}"
        end
      end

      def gems_lines(density)
        grouped = Payload.notable_gems(context).group_by { |g| g[:category]&.to_s || "other" }
        return [] if grouped.empty?

        names = ->(list) { list.map { |g| g[:name] } }
        case density
        when :summary then [ "## Gems", *grouped.map { |cat, list| Budget.list(names.(list), lead: "- **#{cat}**: ") }, "" ]
        when :overview then grouped.map { |cat, list| Budget.list(names.(list), lead: "- #{cat}: ") }
        when :full
          [ "## Notable Gems", *grouped.sort.flat_map { |cat, list| [ "### #{cat.capitalize}", *list.map { |g| "- **#{g[:name]}** (#{g[:version]}): #{g[:note]}" } ] } ]
        else raise ArgumentError, "no gems density #{density}"
        end
      end

      # The booted conventions' architecture and patterns; the static tier reads none.
      def architecture_lines(density)
        return [] unless Payload.section(context, :conventions)

        arch = Payload.architecture(context).map { |a| arch_labels_hash[a] || a }
        patterns = Payload.patterns(context).map { |p| pattern_labels_hash[p] || p }
        case density
        when :summary then [ *arch, *patterns.first(Budget.cap(:patterns)) ].map { |label| "- #{label}" }
        when :overview then arch.first(Budget.cap(:architecture)).map { |label| "- #{label}" }
        when :full
          [ (Budget.list(arch, lead: "- **Architecture:** ") if arch.any?), (Budget.list(patterns, lead: "- **Patterns:** ") if patterns.any?) ].compact
        else raise ArgumentError, "no architecture density #{density}"
        end
      end

      # The filters ApplicationController runs on every request, or nil.
      def before_actions_line(lead)
        names = detect_before_actions
        Budget.list(names, lead: lead) if names.any?
      end
    end
  end
end
